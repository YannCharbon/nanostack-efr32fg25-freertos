#!/usr/bin/env python3
"""Turn the PEM test credentials into apps/common/certs.c.

usage: tools/pem2c.py <dir with ca_cert.pem br_cert.pem br_key.pem node_cert.pem node_key.pem> <out.c>

The arrays are NUL-terminated and their length includes the NUL, as
mbedTLS needs for PEM input (same as wsbrd's read_cert()).
"""
import os
import sys

FILES = [
    ("ca_cert", "ca_cert.pem"),
    ("br_cert", "br_cert.pem"),
    ("br_key", "br_key.pem"),
    ("node_cert", "node_cert.pem"),
    ("node_key", "node_key.pem"),
]


def c_string(text):
    out = []
    for line in text.splitlines():
        out.append('    "%s\\n"' % line.replace("\\", "\\\\").replace('"', '\\"'))
    return "\n".join(out)


def main():
    src, dst = sys.argv[1], sys.argv[2]
    parts = [
        "/*",
        " * GENERATED by tools/pem2c.py - do not edit.",
        " * Source: %s" % "/".join(os.path.abspath(src).split(os.sep)[-2:]),
        " * Demo Wi-SUN PKI (CN \"Wi-SUN Demo Root CA\") from the emulator's examples/.",
        " * TEST CREDENTIALS ONLY: the private keys are public.",
        " */",
        '#include "certs.h"',
        "",
    ]
    for name, fname in FILES:
        with open(os.path.join(src, fname), encoding="ascii") as f:
            text = f.read()
        parts.append("const char cert_%s_pem[] =\n%s;" % (name, c_string(text)))
        parts.append("const unsigned cert_%s_pem_len = sizeof(cert_%s_pem);" % (name, name))
        parts.append("")
    with open(dst, "w", encoding="ascii") as f:
        f.write("\n".join(parts))


if __name__ == "__main__":
    main()
